//! Deterministic Rust source for the GPUI 0.2.2 target.

use std::fmt::Write;

use crate::ir::{
    AlignItems, AlignSelf, BoxSizing, Color, ControlKind, Cursor, Display, EdgeInset,
    FlexDirection, FlexWrap, IrNode, JustifyContent, LetterSpacing, LineHeight, NodeKind, Position,
    SceneIr, TextAlign, Typography,
};

use crate::ir::layout::ratio_border_size;
use crate::ir::paint::{InteractionPaint, RadioBackground, StatePaint};

use super::{Capability, CapabilityGap, TargetCapabilities, TargetEmission, TargetEmitter};

pub struct GpuiTarget;

impl TargetEmitter for GpuiTarget {
    type Artifact = String;

    fn target_id(&self) -> &'static str {
        "gpui"
    }

    fn capabilities(&self) -> TargetCapabilities {
        TargetCapabilities::all()
    }

    fn emit(&self, scene: &SceneIr) -> TargetEmission<Self::Artifact> {
        emit_scene(scene, false, &[], true)
    }
}

impl GpuiTarget {
    /// Attach debug selectors keyed by stable Scene IR node identifiers.
    /// GPUI's test context uses them to report the actual element bounds.
    pub fn emit_with_debug_bounds(&self, scene: &SceneIr) -> TargetEmission<String> {
        emit_scene(scene, true, &[], true)
    }

    /// Emit the custom Neon Glass overlay, with source-resolved hover text colors
    /// and static input paint controlled by its host.
    pub fn emit_with_hover_colors(
        &self,
        scene: &SceneIr,
        colors: &[(String, Color)],
    ) -> TargetEmission<String> {
        emit_scene(scene, true, colors, false)
    }
}

struct EmissionContext<'a> {
    scene: &'a SceneIr,
    debug_bounds: bool,
    hover_colors: &'a [(String, Color)],
    standard_interactivity: bool,
    has_focus_paint: bool,
    viewport_height: bool,
    uses_letter_spacing: bool,
    uses_state_div: bool,
}

fn emit_scene(
    scene: &SceneIr,
    debug_bounds: bool,
    hover_colors: &[(String, Color)],
    standard_interactivity: bool,
) -> TargetEmission<String> {
    let has_editable_inputs = standard_interactivity
        && scene.nodes.iter().any(|node| {
            node.control_kind
                .as_ref()
                .and_then(ControlKind::text_input_value)
                .is_some()
        });
    let has_focus_paint = standard_interactivity
        && scene.nodes.iter().any(|node| {
            node.control_kind.is_some()
                && node
                    .paint
                    .interaction
                    .as_ref()
                    .is_some_and(InteractionPaint::uses_focus)
        });
    let radios: Vec<_> = scene
        .nodes
        .iter()
        .filter_map(|node| match node.control_kind.as_ref() {
            Some(ControlKind::Radio(radio)) if standard_interactivity => Some((&node.id, radio)),
            _ => None,
        })
        .collect();
    let has_radios = !radios.is_empty();
    let has_tab_navigation = has_editable_inputs || has_focus_paint || has_radios;
    let mut rust = String::from(
        "// Generated by css-gpui.\n\
             use gpui::{div, prelude::*};\n\n\
             pub fn render_scene(on_action: fn(&str, &mut gpui::Window, &mut gpui::App)) -> impl IntoElement {\n\
             \x20   let _ = on_action;\n",
    );
    let indent = if has_radios {
        rust.push_str("    SceneRadioScene {\n        options: &[\n");
        for (id, radio) in &radios {
            writeln!(
                rust,
                "            SceneRadioOption {{ id: {id:?}, name: {:?}, checked: {} }},",
                radio.name, radio.checked
            )
            .unwrap();
        }
        let app = if scene
            .nodes
            .iter()
            .any(|node| radio_background(scene, node).is_some())
        {
            "cx"
        } else {
            "_cx"
        };
        writeln!(
            rust,
            "        ],\n        render: move |radios: gpui::Entity<SceneRadioState>, {app}: &gpui::App| {{"
        )
        .unwrap();
        12
    } else {
        4
    };
    let viewport_height = scene.nodes.iter().any(|node| {
        node.layout.bottom.is_some()
            && (node.layout.position == Position::Fixed
                || (node.layout.position == Position::Absolute && node.parent_id.is_none()))
    });
    let height = if viewport_height { ".h_full()" } else { "" };
    writeln!(rust, "{:indent$}div().flex().flex_col().w_full(){height}", "").unwrap();
    let mut declared_loss = Vec::new();
    let mut context = EmissionContext {
        scene,
        debug_bounds,
        hover_colors,
        standard_interactivity,
        has_focus_paint,
        viewport_height,
        uses_letter_spacing: false,
        uses_state_div: false,
    };
    let child_indent = indent + 4;
    emit_children(
        &mut rust,
        &mut context,
        None,
        child_indent,
        &mut declared_loss,
    );
    if has_tab_navigation {
        writeln!(rust, "{:child_indent$}.map(SceneTabNavigation)", "").unwrap();
    }
    if has_radios {
        rust.push_str("        },\n    }\n");
    }
    rust.push_str("}\n");
    emit_assets(&mut rust, scene);
    if context.uses_letter_spacing {
        rust.push_str(include_str!("gpui_spaced_text.rs"));
    }
    if has_tab_navigation {
        rust.push_str(include_str!("gpui_tab_navigation.rs"));
    }
    if has_editable_inputs || context.uses_state_div {
        rust.push_str(include_str!("gpui_state_paint.rs"));
    }
    if context.uses_state_div {
        rust.push_str(include_str!("gpui_state_div.rs"));
    }
    if has_editable_inputs {
        rust.push_str(include_str!("gpui_text_input.rs"));
    }
    if has_radios {
        rust.push_str(include_str!("gpui_radio.rs"));
    }
    TargetEmission {
        artifact: rust,
        declared_loss,
    }
}

fn radio_background<'a>(scene: &SceneIr, node: &'a IrNode) -> Option<&'a RadioBackground> {
    let background = node.paint.radio_background.as_ref()?;
    (node.kind == NodeKind::Box
        && node.paint.interaction.is_none()
        && scene.nodes.iter().any(|node| {
            node.id == background.radio && matches!(node.control_kind, Some(ControlKind::Radio(_)))
        }))
    .then_some(background)
}

// A long builder chain stores each intermediate Div on the Windows debug
// stack. Wide sibling lists build and erase each element in its own closure.
fn emit_children(
    rust: &mut String,
    context: &mut EmissionContext<'_>,
    parent: Option<&IrNode>,
    indent: usize,
    losses: &mut Vec<CapabilityGap>,
) {
    let parent_id = parent.map(|node| node.id.as_str());
    let children: Vec<_> = context
        .scene
        .nodes
        .iter()
        .filter(|node| {
            if node.layout.position == Position::Fixed {
                parent.is_none()
            } else {
                node.parent_id.as_deref() == parent_id
            }
        })
        .collect();
    if children.len() <= 16 {
        for child in children {
            emit_child(rust, context, child, parent, indent, losses, false);
        }
    } else {
        writeln!(rust, "{:indent$}.children([", "").unwrap();
        for child in children {
            emit_child(rust, context, child, parent, indent + 4, losses, true);
        }
        writeln!(rust, "{:indent$}])", "").unwrap();
    }
}

fn emit_child(
    rust: &mut String,
    context: &mut EmissionContext<'_>,
    node: &IrNode,
    parent: Option<&IrNode>,
    indent: usize,
    losses: &mut Vec<CapabilityGap>,
    array_item: bool,
) {
    let checked_background = context
        .standard_interactivity
        .then(|| radio_background(context.scene, node))
        .flatten();
    if node.paint.radio_background.is_some() && checked_background.is_none() {
        declare_loss(node, Capability::InteractionPaint, losses);
    }
    let positioned_text = node.kind == NodeKind::Text
        && matches!(node.layout.position, Position::Absolute | Position::Fixed);
    if node.kind == NodeKind::Text
        && !positioned_text
        && (node.typography.is_none()
            || parent.and_then(|p| p.typography.as_ref()) == node.typography.as_ref())
    {
        let text = node.text_content.as_deref().unwrap_or_default();
        let text_child = native_text(node, text, context, losses);
        if array_item {
            writeln!(rust, "{:indent$}{text_child}.into_any_element(),", "").unwrap();
        } else {
            writeln!(rust, "{:indent$}.child({text_child})", "").unwrap();
        }
        return;
    }

    let (opening, closing) = if array_item {
        ("(|| {", "})().into_any_element(),")
    } else {
        (".child(", ")")
    };
    writeln!(rust, "{:indent$}{opening}", "").unwrap();
    let element = match &node.kind {
        NodeKind::Svg(_) => format!(
            "gpui::img(gpui::ImageSource::Resource(gpui::Resource::Embedded({:?}.into())))",
            svg_asset_path(node)
        ),
        _ => "div()".to_owned(),
    };
    writeln!(rust, "{:width$}{element}", "", width = indent + 4).unwrap();
    let style_indent = indent + 8;
    let mut method = |call: &str| writeln!(rust, "{:style_indent$}.{call}", "").unwrap();
    emit_layout(node, parent, &mut method, losses);
    if context.viewport_height
        && parent.is_none()
        && !matches!(node.layout.position, Position::Absolute | Position::Fixed)
    {
        // The definite root height anchors viewport-relative boxes. Its in-flow
        // children still keep their own heights as they would in block flow.
        method("flex_shrink_0()");
    }
    // GPUI uses physical alignment. The source subset has left-to-right inline flow.
    if node.layout.text_align != parent.and_then(|parent| parent.layout.text_align) {
        match node.layout.text_align {
            Some(TextAlign::Start | TextAlign::Left) => method("text_left()"),
            Some(TextAlign::Center) => method("text_center()"),
            Some(TextAlign::End | TextAlign::Right) => method("text_right()"),
            None => {}
        }
    }
    if context.debug_bounds && !matches!(node.kind, NodeKind::Svg(_)) {
        method(&format!("debug_selector(|| {:?}.to_owned())", node.id));
    }
    if positioned_text {
        method("whitespace_nowrap()");
    }
    if let Some(color) = &node.paint.background_color {
        emit_color(
            node,
            color,
            "bg",
            Capability::Background,
            &mut method,
            losses,
        );
    }
    if let Some(background) = checked_background {
        emit_color(
            node,
            &background.color,
            "bg",
            Capability::Background,
            &mut |call| {
                method(&format!(
                    "when(radios.read(cx).is_checked({:?}), |element| element.{call})",
                    background.radio,
                ))
            },
            losses,
        );
    }
    if let Some(border) = &node.paint.border {
        method(&format!("border(gpui::px({:?}))", border.width));
        emit_color(
            node,
            &border.color,
            "border_color",
            Capability::Border,
            &mut method,
            losses,
        );
    }
    if let Some(radius) = node.paint.border_radius {
        method(&format!("rounded(gpui::px({radius:?}))"));
    }
    if node.paint.cursor == Some(Cursor::Pointer) {
        method("cursor_pointer()");
    }
    if let Some(typography) = node.typography.as_ref()
        && parent.and_then(|p| p.typography.as_ref()) != Some(typography)
    {
        emit_typography(node, typography, &mut method, losses);
    }
    if let Some((_, color)) = context.hover_colors.iter().find(|(id, _)| id == &node.id) {
        emit_color(
            node,
            color,
            "text_color",
            Capability::Typography,
            &mut |call| method(&format!("hover(|style| style.{call})")),
            losses,
        );
    }
    let mut state_paint = None;
    if context.standard_interactivity
        && let Some(interaction) = node.paint.interaction.as_ref()
    {
        if matches!(node.kind, NodeKind::Svg(_) | NodeKind::Text)
            || matches!(node.control_kind, Some(ControlKind::Radio(_)))
            || (interaction.uses_focus() && node.control_kind.is_none())
        {
            declare_loss(node, Capability::InteractionPaint, losses);
        } else {
            if let Some(color) = interaction.resting_text_color.as_ref() {
                emit_color(
                    node,
                    color,
                    "text_color",
                    Capability::Typography,
                    &mut method,
                    losses,
                );
            }
            let hover = state_style(node, &interaction.hover, losses);
            let focus = state_style(node, &interaction.focus, losses);
            let hover_focus = state_style(node, &interaction.hover_focus, losses);
            state_paint = Some(format!(
                "Some(SceneStatePaint {{ hover: {hover}, focus: {focus}, hover_focus: {hover_focus} }})"
            ));
        }
    }
    if node.control_kind == Some(ControlKind::Button) {
        method(&format!("id({:?})", node.id));
        method(&format!(
            "on_click(move |_, window, cx| on_action({:?}, window, cx))",
            node.id
        ));
    }
    if matches!(&node.kind, NodeKind::Svg(_)) {
        writeln!(rust, "{:indent$}{closing}", "").unwrap();
        return;
    }
    if let Some(value) = node
        .control_kind
        .as_ref()
        .and_then(ControlKind::text_input_value)
    {
        method("overflow_hidden()");
        if has_letter_spacing(node) {
            declare_loss(node, Capability::LetterSpacing, losses);
        }
        if context.standard_interactivity {
            let value = value.replace(['\r', '\n'], "");
            let placeholder = node
                .text_content
                .as_deref()
                .unwrap_or_default()
                .replace(['\r', '\n'], "");
            let padding = &node.layout.padding;
            let [left, right, top, bottom] =
                [padding.left, padding.right, padding.top, padding.bottom];
            let state_paint = state_paint.as_deref().unwrap_or("None");
            method(&format!(
                "map(|element| SceneTextInput {{ element, id: {:?}, value: {value:?}, placeholder: {placeholder:?}, padding: [{left:?}, {right:?}, {top:?}, {bottom:?}], state_paint: {state_paint} }})",
                node.id
            ));
        } else {
            declare_loss(node, Capability::TextInputControl, losses);
            if let Some(text) = (!value.is_empty())
                .then_some(value)
                .or(node.text_content.as_deref())
            {
                let left = node.layout.padding.left;
                let top = node.layout.padding.top;
                let right = node.layout.padding.right;
                let end_edge = if node.layout.text_align.is_some() {
                    format!(".right(gpui::px({right:?}))")
                } else {
                    String::new()
                };
                method(&format!(
                    "child(div().absolute().left(gpui::px({left:?})){end_edge}.top(gpui::px({top:?})).whitespace_nowrap().child({text:?}))"
                ));
            }
        }
        writeln!(rust, "{:indent$}{closing}", "").unwrap();
        return;
    }
    if let Some(ControlKind::Radio(radio)) = node.control_kind.as_ref() {
        if context.standard_interactivity {
            let checked_paint = state_style(node, &radio.checked_paint, losses);
            method(&format!("id({:?})", node.id));
            method(&format!(
                "map(|element| SceneRadio {{ element, state: radios.clone(), id: {:?}, checked_paint: {checked_paint} }})",
                node.id
            ));
        } else {
            declare_loss(node, Capability::RadioControl, losses);
        }
        writeln!(rust, "{:indent$}{closing}", "").unwrap();
        return;
    }
    let mut is_radio_label = false;
    if let NodeKind::RadioLabel { target } = &node.kind {
        if context.standard_interactivity
            && context.scene.nodes.iter().any(|node| {
                &node.id == target && matches!(node.control_kind, Some(ControlKind::Radio(_)))
            })
        {
            method(&format!("id({:?})", node.id));
            method(&format!(
                "on_click(SceneRadioState::activate(radios.clone(), {target:?}))"
            ));
            is_radio_label = true;
        } else {
            declare_loss(node, Capability::RadioControl, losses);
        }
    }
    if let Some(text) = node.text_content.as_deref() {
        let text_child = native_text(node, text, context, losses);
        method(&format!("child({text_child})"));
    }
    emit_children(rust, context, Some(node), style_indent, losses);
    let is_button = node.control_kind == Some(ControlKind::Button);
    let focusable = context.has_focus_paint && is_button;
    if state_paint.is_some() || focusable {
        context.uses_state_div = true;
        let state_paint = state_paint.as_deref().unwrap_or("None");
        if !is_button && !is_radio_label {
            writeln!(rust, "{:style_indent$}.id({:?})", "", node.id).unwrap();
        }
        writeln!(
            rust,
            "{:style_indent$}.map(|element| SceneStateDiv {{ element, id: {:?}, focusable: {focusable}, state_paint: {state_paint} }})",
            "", node.id
        ).unwrap();
    }
    writeln!(rust, "{:indent$}{closing}", "").unwrap();
}

fn state_style(node: &IrNode, paint: &StatePaint, losses: &mut Vec<CapabilityGap>) -> String {
    let mut style = "|style| style".to_owned();
    for (color, method, capability) in [
        (&paint.background_color, "bg", Capability::Background),
        (&paint.border_color, "border_color", Capability::Border),
        (&paint.text_color, "text_color", Capability::Typography),
    ] {
        if let Some(color) = color {
            emit_color(
                node,
                color,
                method,
                capability,
                &mut |call| {
                    write!(style, ".{call}").unwrap();
                },
                losses,
            );
        }
    }
    style
}

fn has_letter_spacing(node: &IrNode) -> bool {
    matches!(node.letter_spacing, Some(LetterSpacing::Length { value }) if value != 0.0)
}

fn native_text(
    node: &IrNode,
    text: &str,
    context: &mut EmissionContext<'_>,
    losses: &mut Vec<CapabilityGap>,
) -> String {
    if let Some(LetterSpacing::Length { value }) = node.letter_spacing
        && value != 0.0
        && !text.is_empty()
    {
        // A single ASCII word has no wrapping, bidi, or grapheme boundary rules.
        if text.bytes().all(|byte| byte.is_ascii_alphanumeric()) {
            context.uses_letter_spacing = true;
            return format!("SceneSpacedText {{ text: {text:?}, spacing: {value:?} }}");
        }
        declare_loss(node, Capability::LetterSpacing, losses);
    }
    format!("{text:?}")
}

fn svg_asset_path(node: &IrNode) -> String {
    format!("css-gpui/{}.svg", node.id)
}

fn emit_assets(rust: &mut String, scene: &SceneIr) {
    let artwork: Vec<_> = scene
        .nodes
        .iter()
        .filter_map(|node| match &node.kind {
            NodeKind::Svg(markup) => Some((svg_asset_path(node), markup)),
            _ => None,
        })
        .collect();
    if artwork.is_empty() {
        rust.push_str("\npub fn scene_assets() -> impl gpui::AssetSource {\n    ()\n}\n");
        return;
    }

    rust.push_str(
        "\nstruct SceneAssets;\n\n\
         pub fn scene_assets() -> impl gpui::AssetSource {\n\
         \x20   SceneAssets\n\
         }\n\n\
         impl gpui::AssetSource for SceneAssets {\n\
         \x20   fn load(&self, path: &str) -> gpui::Result<Option<std::borrow::Cow<'static, [u8]>>> {\n\
         \x20       let bytes: Option<&'static [u8]> = match path {\n",
    );
    for (path, markup) in &artwork {
        writeln!(rust, "            {path:?} => Some({markup:?}.as_bytes()),").unwrap();
    }
    rust.push_str(
        "            _ => None,\n\
         \x20       };\n\
         \x20       Ok(bytes.map(std::borrow::Cow::Borrowed))\n\
         \x20   }\n\n\
         \x20   fn list(&self, path: &str) -> gpui::Result<Vec<gpui::SharedString>> {\n\
         \x20       Ok([\n",
    );
    for (path, _) in &artwork {
        writeln!(rust, "            {path:?},").unwrap();
    }
    rust.push_str(
        "        ].into_iter().filter(|asset| asset.starts_with(path)).map(gpui::SharedString::from).collect())\n\
         \x20   }\n\
         }\n",
    );
}

fn emit_layout(
    node: &IrNode,
    parent: Option<&IrNode>,
    method: &mut impl FnMut(&str),
    losses: &mut Vec<CapabilityGap>,
) {
    let layout = &node.layout;
    match layout.display {
        Display::Block => method("block()"),
        Display::Grid => method("grid()"),
        Display::Flex | Display::InlineFlex => {
            method("flex()");
            if layout.display == Display::InlineFlex
                && !parent.is_some_and(|p| {
                    matches!(p.layout.display, Display::Flex | Display::InlineFlex)
                })
            {
                declare_loss(node, Capability::FlexLayout, losses);
            }
        }
    }
    if layout.flex_direction == Some(FlexDirection::Column) {
        method("flex_col()");
    }
    match layout.flex_wrap {
        Some(FlexWrap::Nowrap) => method("flex_nowrap()"),
        Some(FlexWrap::Wrap) => method("flex_wrap()"),
        Some(FlexWrap::WrapReverse) => method("flex_wrap_reverse()"),
        None => {}
    }
    if layout.align_items == Some(AlignItems::Center) {
        method("items_center()");
    }
    match layout.justify_content {
        Some(JustifyContent::Center) => method("justify_center()"),
        Some(JustifyContent::SpaceBetween) => method("justify_between()"),
        None => {}
    }
    let alignment = match layout.align_self {
        Some(AlignSelf::FlexStart) => Some("FlexStart"),
        Some(AlignSelf::Center) => Some("Center"),
        Some(AlignSelf::End) => Some("End"),
        _ => None,
    };
    if let Some(alignment) = alignment {
        method(&format!(
            "map(|mut element| {{ element.style().align_self = Some(gpui::AlignSelf::{alignment}); element }})"
        ));
    }
    if matches!(layout.position, Position::Absolute | Position::Fixed) {
        method("absolute()");
        length(method, "left", layout.left);
        length(method, "top", layout.top);
        length(method, "right", layout.right);
        length(method, "bottom", layout.bottom);
    }
    let border = node
        .paint
        .border
        .as_ref()
        .map_or(0.0, |border| 2.0 * border.width);
    let padding = &layout.padding;
    let insets = [
        padding.left + padding.right + border,
        padding.top + padding.bottom + border,
    ];
    let [inline_extra, block_extra] = if layout.box_sizing == BoxSizing::ContentBox {
        insets
    } else {
        [0.0; 2]
    };
    let mut sizes = [
        layout.width.map(|width| width + inline_extra),
        layout.height.map(|height| height + block_extra),
    ];
    if let Some(ratio) = layout.aspect_ratio {
        if let Some(border_size) = ratio_border_size(
            [layout.width, layout.height],
            ratio,
            insets,
            &layout.box_sizing,
        ) {
            sizes = border_size.map(Some);
        } else {
            declare_loss(node, Capability::AspectRatio, losses);
        }
    }
    length(method, "w", sizes[0]);
    length(method, "h", sizes[1]);
    length(
        method,
        "min_w",
        layout.min_width.map(|width| width + inline_extra),
    );
    length(
        method,
        "min_h",
        layout.min_height.map(|height| height + block_extra),
    );
    if let Some(grid) = &layout.grid {
        // GPUI explicit fractional tracks have a zero minimum. A single
        // implicit auto track preserves the intrinsic size on an auto axis.
        let rows = grid
            .rows
            .filter(|rows| *rows != 1 || layout.height.is_some());
        for (name, value) in [("grid_rows", rows), ("grid_cols", grid.columns)] {
            if let Some(value) = value {
                method(&format!("{name}({value})"));
            }
        }
        for (name, value) in [
            ("row_start", grid.row_start),
            ("col_start", grid.column_start),
        ] {
            if let Some(value) = value {
                method(&format!("{name}({value})"));
            }
        }
    }
    length(method, "gap", layout.gap);
    edges(method, "m", &layout.margin);
    edges(method, "p", &layout.padding);
}

fn length(method: &mut impl FnMut(&str), name: &str, value: Option<f32>) {
    if let Some(value) = value {
        method(&format!("{name}(gpui::px({value:?}))"));
    }
}

fn edges(method: &mut impl FnMut(&str), prefix: &str, inset: &EdgeInset) {
    for (axis, near, far) in [
        ("x", ("l", inset.left), ("r", inset.right)),
        ("y", ("t", inset.top), ("b", inset.bottom)),
    ] {
        if near.1 == far.1 {
            length(
                method,
                &format!("{prefix}{axis}"),
                (near.1 != 0.0).then_some(near.1),
            );
        } else {
            for (side, value) in [near, far] {
                length(
                    method,
                    &format!("{prefix}{side}"),
                    (value != 0.0).then_some(value),
                );
            }
        }
    }
}

fn emit_typography(
    node: &IrNode,
    typography: &Typography,
    method: &mut impl FnMut(&str),
    losses: &mut Vec<CapabilityGap>,
) {
    match typography.font_family.as_slice() {
        [] => {}
        [family] => method(&format!("font_family({family:?})")),
        [family, fallbacks @ ..] => {
            let fallbacks = fallbacks
                .iter()
                .map(|name| format!("{name:?}.into()"))
                .collect::<Vec<_>>()
                .join(", ");
            method(&format!(
                "font(gpui::Font {{ fallbacks: Some(gpui::FontFallbacks::from_fonts(vec![{fallbacks}])), ..gpui::font({family:?}) }})",
            ));
        }
    }
    length(method, "text_size", Some(typography.font_size));
    method(&format!(
        "font_weight(gpui::FontWeight({}.0))",
        typography.font_weight
    ));
    if let LineHeight::Length { value } = typography.line_height {
        length(method, "line_height", Some(value));
    }
    emit_color(
        node,
        &typography.color,
        "text_color",
        Capability::Typography,
        method,
        losses,
    );
}

fn emit_color(
    node: &IrNode,
    color: &Color,
    method_name: &str,
    capability: Capability,
    method: &mut impl FnMut(&str),
    losses: &mut Vec<CapabilityGap>,
) {
    let Some(hex) = color
        .0
        .strip_prefix('#')
        .filter(|hex| hex.bytes().all(|b| b.is_ascii_hexdigit()))
    else {
        declare_loss(node, capability, losses);
        return;
    };
    let (hex, constructor) = match hex.len() {
        3 | 4 => (
            hex.chars()
                .flat_map(|digit| [digit, digit])
                .collect::<String>(),
            if hex.len() == 3 { "rgb" } else { "rgba" },
        ),
        6 => (hex.to_owned(), "rgb"),
        8 => (hex.to_owned(), "rgba"),
        _ => {
            declare_loss(node, capability, losses);
            return;
        }
    };
    method(&format!("{method_name}(gpui::{constructor}(0x{hex}))"));
}

fn declare_loss(node: &IrNode, capability: Capability, losses: &mut Vec<CapabilityGap>) {
    losses.push(CapabilityGap {
        node_id: node.id.clone(),
        capability,
    });
}
